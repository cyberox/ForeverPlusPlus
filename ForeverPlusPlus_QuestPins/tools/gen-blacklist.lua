-- Regenerates ForeverPlusPlus_QuestPins/Blacklist.lua from Questie's quest blacklist.
--
--   lua5.1 ForeverPlusPlus_QuestPins/tools/gen-blacklist.lua <QuestieQuestBlacklist.lua> [output]
--
-- <QuestieQuestBlacklist.lua> is Database/Corrections/QuestieQuestBlacklist.lua of a Questie
-- checkout (https://github.com/Questie/Questie). The output defaults to
-- ForeverPlusPlus_QuestPins/Blacklist.lua.
--
-- Questie's file is code, not data: it needs its own loader and a few globals. This runs it with
-- stand-ins for them, as an Era-style client (Expansions.Current is Era, no Season of Discovery,
-- no China region, no content phases), and keeps every quest whose entry is on: `true`, or
-- HIDE_ON_MAP, which Questie only hides from its own map but is no use to a pin either. Entries
-- that are `false`, and the Wotlk and Titan Reforged lists, are left out.
local source, target = arg[1], arg[2] or "ForeverPlusPlus_QuestPins/Blacklist.lua"
if not source then
    io.stderr:write("usage: lua5.1 ForeverPlusPlus_QuestPins/tools/gen-blacklist.lua <QuestieQuestBlacklist.lua> [output]\n")
    os.exit(1)
end

local modules = {}
local expansions = { Era = 1, Tbc = 2, Wotlk = 3, Cata = 4, MoP = 5, Current = 1 }

QuestieLoader = {}
function QuestieLoader:CreateModule(name)
    modules[name] = modules[name] or {}
    return modules[name]
end
function QuestieLoader:ImportModule(name)
    if name == "Expansions" then
        return expansions
    end
    modules[name] = modules[name] or {}
    return modules[name]
end
Questie = { Debug = function() end, DEBUG_DEVELOP = 0 } -- every IsXxx is nil: none of them is the client

local chunk, err = loadfile(source)
if not chunk then
    error(err)
end
chunk()

local list = modules.QuestieQuestBlacklist:Load()
local ids = {}
for questID, value in pairs(list) do
    if value then
        ids[#ids + 1] = questID
    end
end
table.sort(ids)

local out = assert(io.open(target, "w"))
out:write("-- Generated by ForeverPlusPlus_QuestPins/tools/gen-blacklist.lua from Questie's quest blacklist; do not edit by hand.\n")
out:write("-- Quest IDs that exist in the data but cannot be picked up in game.\n")
out:write("-- Source: Questie (https://github.com/Questie/Questie), used under the GPLv3.\n")
out:write("local _, mine = ...\n")
out:write("mine.blacklist = {\n")
for _, questID in ipairs(ids) do
    out:write(("    [%d] = true,\n"):format(questID))
end
out:write("}\n")
out:close()
print(("%d quests written to %s"):format(#ids, target))
