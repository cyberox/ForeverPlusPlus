-- Unexplored Areas' Data.lua: every explored area's art on the zone maps, from WorldMapOverlay
-- (an area's size and place on its map art) and WorldMapOverlayTile (its 256 pixel tiles), keyed
-- by map art ID. UiMapXMapArt and UiMap name the zone each art belongs to, for the comments, and
-- only art a map uses is written.
local CSV = require("csv")
local Lua = require("luaout")

local M = {
    path = "ForeverPlusPlus/Modules/Map/WorldMap/UnexploredAreas/Data.lua",
    tables = { "WorldMapOverlay", "WorldMapOverlayTile", "UiMapXMapArt", "UiMap" },
}

local Int = CSV.Int

-- For summary.lua: an area line's key (its map art and place) and the line itself.
function M.Entry(line, state)
    local art = line:match("^    %[(%d+)%] = {")
    if art then
        state.art = art
        return
    end
    local area = line:match("^        { (%d+, %d+, %d+, %d+)")
    if area and state.art then
        return "art " .. state.art .. " area " .. area, line
    end
end

function M.Build(t, build, script)
    local maps = {} -- UiMap ID -> name
    for _, row in ipairs(CSV.Records(t.UiMap, "UiMap", { "ID", "Name_lang" })) do
        maps[Int(row.ID, "UiMap.ID")] = row.Name_lang
    end
    local artMap = {} -- art ID -> lowest UiMap ID that uses it
    for _, row in ipairs(CSV.Records(t.UiMapXMapArt, "UiMapXMapArt", { "UiMapArtID", "UiMapID" })) do
        local art, map = Int(row.UiMapArtID, "UiMapArtID"), Int(row.UiMapID, "UiMapID")
        if not artMap[art] or map < artMap[art] then
            artMap[art] = map
        end
    end

    local tiles = {} -- overlay ID -> tiles
    for _, row in ipairs(CSV.Records(t.WorldMapOverlayTile, "WorldMapOverlayTile",
        { "ID", "RowIndex", "ColIndex", "LayerIndex", "FileDataID", "WorldMapOverlayID" })) do
        local overlay = Int(row.WorldMapOverlayID, "WorldMapOverlayID")
        tiles[overlay] = tiles[overlay] or {}
        table.insert(tiles[overlay], {
            layer = Int(row.LayerIndex, "LayerIndex"), row = Int(row.RowIndex, "RowIndex"),
            col = Int(row.ColIndex, "ColIndex"), id = Int(row.ID, "ID"),
            file = Int(row.FileDataID, "FileDataID"),
        })
    end

    local byArt = {}
    for _, row in ipairs(CSV.Records(t.WorldMapOverlay, "WorldMapOverlay",
        { "ID", "UiMapArtID", "TextureWidth", "TextureHeight", "OffsetX", "OffsetY" })) do
        local art, id = Int(row.UiMapArtID, "UiMapArtID"), Int(row.ID, "ID")
        -- An area with no tiles (some are 0 by 0) draws nothing, so it's left out.
        if artMap[art] and tiles[id] then
            byArt[art] = byArt[art] or {}
            table.insert(byArt[art], {
                id = id,
                w =Int(row.TextureWidth, "TextureWidth"), h = Int(row.TextureHeight, "TextureHeight"),
                x = Int(row.OffsetX, "OffsetX"), y = Int(row.OffsetY, "OffsetY"),
            })
        end
    end

    -- Maps by zone name, then art ID; areas top to bottom, then left to right; tiles by row and
    -- column, as the game draws them.
    local arts = {}
    for art in pairs(byArt) do
        arts[#arts + 1] = art
    end
    table.sort(arts, function(a, b)
        local na, nb = maps[artMap[a]] or "", maps[artMap[b]] or ""
        if na ~= nb then
            return na < nb
        end
        return a < b
    end)

    local out = {
        "-- The art of every explored area on the zone maps, from the game's WorldMapOverlay and",
        "-- WorldMapOverlayTile tables, keyed by map art ID (C_Map.GetMapArtID). The game only lists",
        "-- the areas a character has explored, so the rest have to come from here. Each area is",
        "-- { width, height, x, y, file IDs... }: its size and top left corner in map pixels, and its",
        "-- 256 pixel tiles by row.",
        "--",
        "-- Generated by " .. script .. " from wago.tools' tables for build " .. build .. ".",
        "-- Don't edit it by hand: run the script again after a patch.",
        "local _, ns = ...",
        "",
        "ns.modules.WorldMap.internal.unexploredAreas.overlays = {",
    }
    for _, art in ipairs(arts) do
        local map = artMap[art]
        out[#out + 1] = ("    [%d] = { -- %s (%d)"):format(art, Lua.Comment(maps[map] or "?"), map)
        local areas = byArt[art]
        table.sort(areas, function(a, b)
            if a.y ~= b.y then
                return a.y < b.y
            elseif a.x ~= b.x then
                return a.x < b.x
            end
            return a.id < b.id
        end)
        for _, area in ipairs(areas) do
            local list = tiles[area.id]
            table.sort(list, function(a, b)
                if a.layer ~= b.layer then
                    return a.layer < b.layer
                elseif a.row ~= b.row then
                    return a.row < b.row
                elseif a.col ~= b.col then
                    return a.col < b.col
                end
                return a.id < b.id
            end)
            local fields = { area.w, area.h, area.x, area.y }
            for _, tile in ipairs(list) do
                fields[#fields + 1] = tile.file
            end
            out[#out + 1] = "        { " .. table.concat(fields, ", ") .. " },"
        end
        out[#out + 1] = "    },"
    end
    out[#out + 1] = "}"
    return table.concat(out, "\n") .. "\n"
end

return M
