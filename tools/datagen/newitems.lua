-- Lib/Generated/NewItems.lua: the items Classic never had, as runs of item IDs: every ID in this
-- build's Item table that isn't in the Item table of the last Classic Era build before Season of
-- Discovery (generate.lua's CLASSIC_BUILD). That build is fixed, so the same Forever build gives
-- the same bytes. Season of Discovery's items count as new: Classic didn't have them either.
local CSV = require("csv")

local M = {
    path = "ForeverPlusPlus/Lib/Generated/NewItems.lua",
    tables = { "Item" },
    classic = { "Item" },
}

local Int = CSV.Int

-- For summary.lua: a run's key (its first ID) and the line itself.
function M.Entry(line)
    local first = line:match("^    (%d+), %d+,$")
    if first then
        return "items from " .. first, line
    end
end

function M.Build(t, build, script, _, classicBuild)
    local classic = {}
    for _, row in ipairs(CSV.Records(t["Classic.Item"], "Classic Item", { "ID" })) do
        classic[Int(row.ID, "Classic Item.ID")] = true
    end
    local ids, highest = {}, 0
    for _, row in ipairs(CSV.Records(t.Item, "Item", { "ID" })) do
        local id = Int(row.ID, "Item.ID")
        if id > highest then
            highest = id
        end
        if not classic[id] then
            ids[#ids + 1] = id
        end
    end
    if #ids == 0 or not next(classic) then
        error("no new items, or no Classic items: one of the tables is wrong")
    end
    table.sort(ids)

    local out = {
        "-- The items Classic never had: runs of item IDs, as first and last, in order. An item is new",
        "-- when its ID is in a run, or above `highest`, the highest ID the game had when this was made.",
        "-- From the game's Item table, less the Item table of Classic Era build " .. classicBuild .. ", the",
        "-- last one before Season of Discovery.",
        "--",
        "-- Generated by " .. script .. " from wago.tools' tables for build " .. build .. ".",
        "-- Don't edit it by hand: run the script again after a patch.",
        "local _, ns = ...",
        "",
        "ns.TableData = ns.TableData or {}",
        "ns.TableData.newItemsHighest = " .. highest,
        "ns.TableData.newItems = {",
    }
    local first, last = ids[1], ids[1]
    for i = 2, #ids + 1 do
        local id = ids[i]
        if id ~= last + 1 then
            out[#out + 1] = ("    %d, %d,"):format(first, last)
            first = id
        end
        last = id
    end
    out[#out + 1] = "}"
    return table.concat(out, "\n") .. "\n"
end

return M
