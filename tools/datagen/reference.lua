-- tools/datagen/Reference.txt: what the tables say about data the addon keeps by hand, so a new
-- build's diff shows what to look at. Not shipped and not read by the addon.
--   Instances: the Map table's dungeons and raids, marked when Lib/Instances.lua lacks one.
--   Flight points: TaxiNodes placed on their zone with UiMapAssignment, in /way percent, as
--   Points of Interest's Data.lua has them.
--   Transport stops: the stops (a Delay) of TaxiPathNode's paths, placed the same way.
local CSV = require("csv")
local Lua = require("luaout")

local M = {
    path = "tools/datagen/Reference.txt",
    tables = { "Map", "TaxiNodes", "TaxiPathNode", "UiMapAssignment", "UiMap" },
}

local Int, Number = CSV.Int, CSV.Number

local UNUSED = 1024 -- TaxiNodes.Flags when it's the only flag: a node no flight master offers

local function readFile(path)
    local file = io.open(path, "rb")
    if not file then
        return ""
    end
    local text = file:read("*a")
    file:close()
    return text
end

-- Zone and city maps by continent, with their rectangles in world yards.
local function zonesOf(t)
    local maps = {}
    for _, row in ipairs(CSV.Records(t.UiMap, "UiMap", { "ID", "Name_lang", "Type", "System" })) do
        maps[Int(row.ID, "UiMap.ID")] = {
            name = row.Name_lang, type = Int(row.Type, "Type"), system = Int(row.System, "System"),
        }
    end
    local zones = {}
    for _, row in ipairs(CSV.Records(t.UiMapAssignment, "UiMapAssignment", { "ID", "UiMapID",
        "MapID", "Region_0", "Region_1", "Region_3", "Region_4" })) do
        local id = Int(row.UiMapID, "UiMapID")
        local map = maps[id]
        if map and map.type == 3 and map.system == 0 then
            local zone = {
                id = id, name = map.name, row = Int(row.ID, "ID"),
                minX = Number(row.Region_0), minY = Number(row.Region_1),
                maxX = Number(row.Region_3), maxY = Number(row.Region_4),
            }
            local continent = Int(row.MapID, "MapID")
            zones[continent] = zones[continent] or {}
            table.insert(zones[continent], zone)
        end
    end
    return zones
end

-- A world position as "Zone (map ID) x, y" on every zone map whose rectangle holds it, the one
-- it's deepest inside first (the rectangles overlap, and only the client's terrain says which zone
-- a spot is really in), or "continent N x, y" when none does.
local function place(zones, continent, x, y)
    local found = {}
    for _, zone in ipairs(zones[continent] or {}) do
        if x >= zone.minX and x <= zone.maxX and y >= zone.minY and y <= zone.maxY then
            local px = (zone.maxY - y) / (zone.maxY - zone.minY) * 100
            local py = (zone.maxX - x) / (zone.maxX - zone.minX) * 100
            found[#found + 1] = {
                depth = math.min(px, 100 - px, py, 100 - py), row = zone.row,
                text = ("%s (%d) %.1f, %.1f"):format(Lua.Comment(zone.name), zone.id, px, py),
            }
        end
    end
    if #found == 0 then
        return ("continent %d %.0f, %.0f"):format(continent, x, y)
    end
    table.sort(found, function(a, b)
        if a.depth ~= b.depth then
            return a.depth > b.depth
        end
        return a.row < b.row
    end)
    local text = {}
    for i, place in ipairs(found) do
        text[i] = place.text
    end
    return table.concat(text, " | ")
end

function M.Build(t, build, script, root)
    local zones = zonesOf(t)
    local out = {
        "What build " .. build .. "'s tables say about data the addon keeps by hand.",
        "Generated by " .. script .. "; don't edit it by hand. Not shipped.",
        "",
        "Instances (Map, InstanceType 1 dungeon, 2 raid); * not in ForeverPlusPlus/Lib/Instances.lua",
    }

    local known = {}
    for id in readFile(root .. "/ForeverPlusPlus/Lib/Instances.lua"):gmatch("=%s*{%s*(%d+)%s*,%s*\"") do
        known[tonumber(id)] = true
    end
    local instances = {}
    for _, row in ipairs(CSV.Records(t.Map, "Map", { "ID", "MapName_lang", "InstanceType" })) do
        local kind = Int(row.InstanceType, "InstanceType")
        if kind == 1 or kind == 2 then
            instances[#instances + 1] = { id = Int(row.ID, "Map.ID"), name = row.MapName_lang, kind = kind }
        end
    end
    table.sort(instances, function(a, b) return a.id < b.id end)
    for _, instance in ipairs(instances) do
        out[#out + 1] = ("%s %5d %-5s %s"):format(known[instance.id] and " " or "*", instance.id,
            instance.kind == 2 and "raid" or "party", Lua.Comment(instance.name))
    end

    out[#out + 1] = ""
    out[#out + 1] = "Flight points (TaxiNodes): ID, side by mount (A, H, N), name, place; unused when"
    out[#out + 1] = "Flags is 1024 alone"
    local nodes = {}
    for _, row in ipairs(CSV.Records(t.TaxiNodes, "TaxiNodes", { "ID", "Name_lang", "Pos_0", "Pos_1",
        "ContinentID", "Flags", "MountCreatureID_0", "MountCreatureID_1" })) do
        nodes[#nodes + 1] = {
            id = Int(row.ID, "TaxiNodes.ID"), name = row.Name_lang,
            x = Number(row.Pos_0), y = Number(row.Pos_1), continent = Int(row.ContinentID),
            flags = Int(row.Flags), horde = Int(row.MountCreatureID_0) ~= 0,
            alliance = Int(row.MountCreatureID_1) ~= 0,
        }
    end
    table.sort(nodes, function(a, b) return a.id < b.id end)
    for _, node in ipairs(nodes) do
        local side = node.alliance and node.horde and "N" or node.alliance and "A"
            or node.horde and "H" or "-"
        out[#out + 1] = ("%5d %s %s: %s%s"):format(node.id, side, Lua.Comment(node.name),
            place(zones, node.continent, node.x, node.y), node.flags == UNUSED and " (unused)" or "")
    end

    out[#out + 1] = ""
    out[#out + 1] = "Transport stops (TaxiPathNode rows with a Delay): path, then each stop in order"
    local paths = {}
    for _, row in ipairs(CSV.Records(t.TaxiPathNode, "TaxiPathNode", { "PathID", "NodeIndex",
        "ContinentID", "Loc_0", "Loc_1", "Delay" })) do
        if Int(row.Delay, "Delay") > 0 then
            local path = Int(row.PathID, "PathID")
            paths[path] = paths[path] or {}
            table.insert(paths[path], {
                index = Int(row.NodeIndex, "NodeIndex"), continent = Int(row.ContinentID),
                x = Number(row.Loc_0), y = Number(row.Loc_1),
            })
        end
    end
    local ids = {}
    for id in pairs(paths) do
        ids[#ids + 1] = id
    end
    table.sort(ids)
    for _, id in ipairs(ids) do
        local stops = paths[id]
        table.sort(stops, function(a, b) return a.index < b.index end)
        local text = {}
        for _, stop in ipairs(stops) do
            text[#text + 1] = place(zones, stop.continent, stop.x, stop.y)
        end
        out[#out + 1] = ("%5d: %s"):format(id, table.concat(text, "; "))
    end
    return table.concat(out, "\n") .. "\n"
end

return M
