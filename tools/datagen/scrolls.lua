-- Lib/Generated/ComprehendScrolls.lua: the scrolls a Mage needs Comprehension to read, from
-- ItemSparse: the items whose RequiredSkill is skill line 3012 (Comprehension). Test items
-- ("[DNT] ...", "Deprecated ...") are left out.
local CSV = require("csv")
local Lua = require("luaout")

local M = {
    path = "ForeverPlusPlus/Lib/Generated/ComprehendScrolls.lua",
    tables = { "ItemSparse" },
}

local Int = CSV.Int

local COMPREHENSION = 3012 -- SkillLine.ID

-- For summary.lua: an item line's key (its ID) and the line itself.
function M.Entry(line)
    local id = line:match("^    %[(%d+)%] = true,")
    if id then
        return "item " .. id, line
    end
end

function M.Build(t, build, script)
    local list = {}
    for _, row in ipairs(CSV.Records(t.ItemSparse, "ItemSparse", { "ID", "Display_lang", "RequiredSkill" })) do
        local name = row.Display_lang
        if Int(row.RequiredSkill, "RequiredSkill") == COMPREHENSION
            and not (name:find("^%[DNT%]") or name:find("^Deprecated")) then
            list[#list + 1] = { id = Int(row.ID, "ItemSparse.ID"), name = name }
        end
    end
    table.sort(list, function(a, b)
        return a.id < b.id
    end)

    local out = {
        "-- The scrolls that need Comprehension, from the game's ItemSparse table (RequiredSkill 3012), by",
        "-- item ID.",
        "--",
        "-- Generated by " .. script .. " from wago.tools' tables for build " .. build .. ".",
        "-- Don't edit it by hand: run the script again after a patch.",
        "local _, ns = ...",
        "",
        "ns.TableData = ns.TableData or {}",
        "ns.TableData.comprehendScrolls = {",
    }
    for _, entry in ipairs(list) do
        out[#out + 1] = ("    [%d] = true, -- %s"):format(entry.id, Lua.Comment(entry.name))
    end
    out[#out + 1] = "}"
    return table.concat(out, "\n") .. "\n"
end

return M
