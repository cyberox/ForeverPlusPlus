-- Lib/Generated/ExplorableMaps.lua: the map art that has areas to explore, from WorldMapOverlay (an
-- area on a map's art) with a tile in WorldMapOverlayTile, by map art ID. The same areas as
-- Unexplored Areas' Data.lua draws, as a set: a city or a dungeon has none, so nothing on its map
-- is ever unexplored. UiMapXMapArt and UiMap name the zone each art belongs to, for the comments.
local CSV = require("csv")
local Lua = require("luaout")

local M = {
    path = "ForeverPlusPlus/Lib/Generated/ExplorableMaps.lua",
    tables = { "WorldMapOverlay", "WorldMapOverlayTile", "UiMapXMapArt", "UiMap" },
}

local Int = CSV.Int

-- For summary.lua: a line's key (its map art) and the line itself.
function M.Entry(line)
    local art = line:match("^    %[(%d+)%] = true,")
    if art then
        return "art " .. art, line
    end
end

function M.Build(t, build, script)
    local maps = {} -- UiMap ID -> name
    for _, row in ipairs(CSV.Records(t.UiMap, "UiMap", { "ID", "Name_lang" })) do
        maps[Int(row.ID, "UiMap.ID")] = row.Name_lang
    end
    local artMap = {} -- art ID -> lowest UiMap ID that uses it
    for _, row in ipairs(CSV.Records(t.UiMapXMapArt, "UiMapXMapArt", { "UiMapArtID", "UiMapID" })) do
        local art, map = Int(row.UiMapArtID, "UiMapArtID"), Int(row.UiMapID, "UiMapID")
        if not artMap[art] or map < artMap[art] then
            artMap[art] = map
        end
    end
    local tiled = {} -- overlay ID -> true: it has art
    for _, row in ipairs(CSV.Records(t.WorldMapOverlayTile, "WorldMapOverlayTile", { "WorldMapOverlayID" })) do
        tiled[Int(row.WorldMapOverlayID, "WorldMapOverlayID")] = true
    end
    local seen, arts = {}, {}
    for _, row in ipairs(CSV.Records(t.WorldMapOverlay, "WorldMapOverlay", { "ID", "UiMapArtID" })) do
        local art = Int(row.UiMapArtID, "UiMapArtID")
        if artMap[art] and tiled[Int(row.ID, "ID")] and not seen[art] then
            seen[art] = true
            arts[#arts + 1] = art
        end
    end
    table.sort(arts)

    local out = {
        "-- The map art that has areas to explore, from the game's WorldMapOverlay and",
        "-- WorldMapOverlayTile tables, by map art ID (C_Map.GetMapArtID). A map whose art isn't here,",
        "-- as a city's or a dungeon's, has nothing to explore.",
        "--",
        "-- Generated by " .. script .. " from wago.tools' tables for build " .. build .. ".",
        "-- Don't edit it by hand: run the script again after a patch.",
        "local _, ns = ...",
        "",
        "ns.TableData = ns.TableData or {}",
        "ns.TableData.explorableMaps = {",
    }
    for _, art in ipairs(arts) do
        local map = artMap[art]
        out[#out + 1] = ("    [%d] = true, -- %s (%d)"):format(art, Lua.Comment(maps[map] or "?"), map)
    end
    out[#out + 1] = "}"
    return table.concat(out, "\n") .. "\n"
end

return M
