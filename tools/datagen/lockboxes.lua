-- Lib/LockboxSkills.lua: the Lockpicking each lockbox item needs, from ItemSparse.LockID -> Lock:
-- the lock's slot whose Type is 2 (a lock type) and whose index is LockType 1 ("Pick Lock") holds
-- the skill. World chests are server objects and in no client table, so they aren't here. Test
-- items ("[DNT] ...", "Deprecated ...") are left out.
local CSV = require("csv")
local Lua = require("luaout")

local M = {
    path = "ForeverPlusPlus/Lib/LockboxSkills.lua",
    tables = { "ItemSparse", "Lock" },
}

local Int = CSV.Int

local LOCK_TYPE = 2 -- Lock.Type_n: the slot names a LockType
local PICK_LOCK = 1 -- LockType.ID of "Pick Lock"

-- For summary.lua: an item line's key (its ID) and the line itself.
function M.Entry(line)
    local id = line:match("^    %[(%d+)%] = %d+,")
    if id then
        return "item " .. id, line
    end
end

function M.Build(t, build, script)
    local columns = { "ID" }
    for n = 0, 7 do
        columns[#columns + 1] = "Type_" .. n
        columns[#columns + 1] = "_Index_" .. n
        columns[#columns + 1] = "Skill_" .. n
    end
    local picks = {} -- lock ID -> Lockpicking
    for _, row in ipairs(CSV.Records(t.Lock, "Lock", columns)) do
        for n = 0, 7 do
            if Int(row["Type_" .. n], "Type") == LOCK_TYPE and Int(row["_Index_" .. n], "_Index") == PICK_LOCK then
                picks[Int(row.ID, "Lock.ID")] = Int(row["Skill_" .. n], "Skill")
                break
            end
        end
    end

    local list = {}
    for _, row in ipairs(CSV.Records(t.ItemSparse, "ItemSparse", { "ID", "Display_lang", "LockID" })) do
        local skill = picks[Int(row.LockID, "LockID")]
        local name = row.Display_lang
        if skill and not (name:find("^%[DNT%]") or name:find("^Deprecated")) then
            list[#list + 1] = { id = Int(row.ID, "ItemSparse.ID"), name = row.Display_lang, skill = skill }
        end
    end
    table.sort(list, function(a, b)
        return a.id < b.id
    end)

    local out = {
        "-- The Lockpicking each lockbox item needs, from the game's ItemSparse (LockID) and Lock tables",
        "-- (the Pick Lock slot's skill), by item ID. World chests aren't in any client table.",
        "--",
        "-- Generated by " .. script .. " from wago.tools' tables for build " .. build .. ".",
        "-- Don't edit it by hand: run the script again after a patch.",
        "local _, ns = ...",
        "",
        "ns.TableData = ns.TableData or {}",
        "ns.TableData.lockboxSkills = {",
    }
    for _, entry in ipairs(list) do
        out[#out + 1] = ("    [%d] = %d, -- %s"):format(entry.id, entry.skill, Lua.Comment(entry.name))
    end
    out[#out + 1] = "}"
    return table.concat(out, "\n") .. "\n"
end

return M
