-- Lib/DisenchantBrackets.lua: which items can be disenchanted, from ItemDisenchantLoot: a
-- bracket per quality, item class (2 weapon, 4 armor), and item level range. The table says
-- nothing of what a bracket gives (that's server data); Lib/Disenchant.lua keeps that by hand and
-- learns the rest in play. Rows for one subclass or expansion only would need more than this
-- writes, so the build fails on one rather than writing a wrong bracket.
local CSV = require("csv")

local M = {
    path = "ForeverPlusPlus/Lib/DisenchantBrackets.lua",
    tables = { "ItemDisenchantLoot" },
}

local Int = CSV.Int

local QUALITY = { [2] = "uncommon", [3] = "rare", [4] = "epic" }
local CLASS = { [2] = "weapon", [4] = "armor" }

-- For summary.lua: a bracket line's key (quality, class, lowest level) and the line itself.
function M.Entry(line)
    local quality, class, low = line:match("^    { (%d+), (%d+), (%d+), %d+ },")
    if quality then
        return ("bracket %s %s %s"):format(quality, class, low), line
    end
end

function M.Build(t, build, script)
    local list = {}
    for _, row in ipairs(CSV.Records(t.ItemDisenchantLoot, "ItemDisenchantLoot", { "Class", "Subclass",
        "Quality", "MinLevel", "MaxLevel", "ExpansionID" })) do
        local class, quality = Int(row.Class, "Class"), Int(row.Quality, "Quality")
        if Int(row.Subclass, "Subclass") ~= -1 or Int(row.ExpansionID, "ExpansionID") ~= -2 then
            error("a bracket for one subclass or expansion: the generator doesn't handle it yet")
        end
        if not (CLASS[class] and QUALITY[quality]) then
            error(("a bracket for class %d quality %d: the generator doesn't name it"):format(class, quality))
        end
        list[#list + 1] = {
            quality = quality, class = class,
            low = Int(row.MinLevel, "MinLevel"), high = Int(row.MaxLevel, "MaxLevel"),
        }
    end
    table.sort(list, function(a, b)
        if a.quality ~= b.quality then
            return a.quality < b.quality
        elseif a.class ~= b.class then
            return a.class < b.class
        end
        return a.low < b.low
    end)

    local out = {
        "-- Which items can be disenchanted: the game's ItemDisenchantLoot brackets, each { quality",
        "-- (Enum.ItemQuality), item class (2 weapon, 4 armor), lowest item level, highest }. What each",
        "-- gives isn't in the client's tables; Lib/Disenchant.lua has that.",
        "--",
        "-- Generated by " .. script .. " from wago.tools' tables for build " .. build .. ".",
        "-- Don't edit it by hand: run the script again after a patch.",
        "local _, ns = ...",
        "",
        "ns.TableData = ns.TableData or {}",
        "ns.TableData.disenchantBrackets = {",
    }
    for _, b in ipairs(list) do
        out[#out + 1] = ("    { %d, %d, %d, %d }, -- %s %s"):format(b.quality, b.class, b.low, b.high,
            QUALITY[b.quality], CLASS[b.class])
    end
    out[#out + 1] = "}"
    return table.concat(out, "\n") .. "\n"
end

return M
