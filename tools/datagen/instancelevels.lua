-- Lib/InstanceLevels.lua: each dungeon's and raid's lowest level as the dungeon finder has it, by
-- instance ID, for Lib/Instances.lua. The finder's entries (LFGDungeons, TypeID 0) carry no
-- instance ID on this client (MapID is 0), so each Map instance (InstanceType 1 or 2) is matched
-- to one: by the finder entry's name, else by its area's ContentTuning (AreaTable.ContentTuningID,
-- the same tuning its finder entry has, which also covers "Deadmines" and the split ones such as
-- Dire Maul's wings). The level is ContentTuning.MinLevelSquish. No table has a highest level.
local CSV = require("csv")
local Lua = require("luaout")

local M = {
    path = "ForeverPlusPlus/Lib/InstanceLevels.lua",
    tables = { "Map", "LFGDungeons", "ContentTuning", "AreaTable" },
}

local Int = CSV.Int

-- For summary.lua: an instance line's key (its ID) and the line itself.
function M.Entry(line)
    local id = line:match("^    %[(%d+)%] = %d+,")
    if id then
        return "instance " .. id, line
    end
end

function M.Build(t, build, script)
    local tuning = {} -- ContentTuning ID -> lowest level
    for _, row in ipairs(CSV.Records(t.ContentTuning, "ContentTuning", { "ID", "MinLevelSquish" })) do
        tuning[Int(row.ID, "ContentTuning.ID")] = Int(row.MinLevelSquish, "MinLevelSquish")
    end
    -- The finder's dungeons and raids by name, and the tunings any of them use.
    local finderByName, finderTunings = {}, {}
    for _, row in ipairs(CSV.Records(t.LFGDungeons, "LFGDungeons", { "Name_lang", "TypeID",
        "ContentTuningID" })) do
        local id = Int(row.ContentTuningID, "LFGDungeons.ContentTuningID")
        if Int(row.TypeID, "LFGDungeons.TypeID") == 0 and tuning[id] and tuning[id] > 0 then
            finderByName[row.Name_lang] = id
            finderTunings[id] = true
        end
    end
    -- Names as "zulfarrak", without a leading "The", for "The Hall of Thanes" and "Hall of Thanes".
    local function plain(name)
        return (name:lower():gsub("^the ", ""):gsub("[^%w]", ""))
    end
    local finderByPlain = {}
    for name, id in pairs(finderByName) do
        finderByPlain[plain(name)] = id
    end
    -- The one finder entry whose name starts the instance's ("Onyxia" for "Onyxia's Lair").
    local function byPrefix(name)
        local found
        for each, id in pairs(finderByPlain) do
            if #each >= 5 and name:sub(1, #each) == each then
                if found and found ~= id then
                    return nil
                end
                found = id
            end
        end
        return found
    end
    -- Area ID -> ContentTuning ID, and an instance's own top-level area's (ContinentID is the
    -- instance's map), only those a finder entry uses: "Zul'Farak" in the finder is the area's.
    local areaTuning, mapTuning = {}, {}
    for _, row in ipairs(CSV.Records(t.AreaTable, "AreaTable", { "ID", "ContinentID", "ParentAreaID",
        "ContentTuningID" })) do
        local id = Int(row.ContentTuningID, "AreaTable.ContentTuningID")
        if finderTunings[id] then
            areaTuning[Int(row.ID, "AreaTable.ID")] = id
            if Int(row.ParentAreaID, "ParentAreaID") == 0 then
                local map = Int(row.ContinentID, "ContinentID")
                mapTuning[map] = mapTuning[map] or id
            end
        end
    end

    local list = {}
    for _, row in ipairs(CSV.Records(t.Map, "Map", { "ID", "MapName_lang", "InstanceType",
        "AreaTableID" })) do
        local kind = Int(row.InstanceType, "InstanceType")
        if kind == 1 or kind == 2 then
            local name = plain(row.MapName_lang)
            local id = finderByName[row.MapName_lang] or finderByPlain[name]
                or areaTuning[Int(row.AreaTableID, "AreaTableID")] or mapTuning[Int(row.ID, "Map.ID")]
                or byPrefix(name)
            if id then
                list[#list + 1] = { id = Int(row.ID, "Map.ID"), name = row.MapName_lang, level = tuning[id] }
            end
        end
    end
    table.sort(list, function(a, b)
        return a.id < b.id
    end)

    local out = {
        "-- Each dungeon's and raid's lowest level as the game's dungeon finder has it (LFGDungeons ->",
        "-- ContentTuning.MinLevelSquish), by instance ID (the Map table's), for Lib/Instances.lua. The",
        "-- finder's entries are matched to instances by name or by the instance's area's tuning.",
        "--",
        "-- Generated by " .. script .. " from wago.tools' tables for build " .. build .. ".",
        "-- Don't edit it by hand: run the script again after a patch.",
        "local _, ns = ...",
        "",
        "ns.TableData = ns.TableData or {}",
        "ns.TableData.instanceLevels = {",
    }
    for _, entry in ipairs(list) do
        out[#out + 1] = ("    [%d] = %d, -- %s"):format(entry.id, entry.level, Lua.Comment(entry.name))
    end
    out[#out + 1] = "}"
    return table.concat(out, "\n") .. "\n"
end

return M
